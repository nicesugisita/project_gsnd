"""경상남도 시·군 이름 정규화 유틸리티"""

import re

# 경상남도 시군 이름 정규화 테이블
_SIGUN_NORMALIZE_MAP = {
    # 시
    "창원": "경상남도 창원시",
    "진주": "경상남도 진주시",
    "통영": "경상남도 통영시",
    "사천": "경상남도 사천시",
    "김해": "경상남도 김해시",
    "밀양": "경상남도 밀양시",
    "거제": "경상남도 거제시",
    "양산": "경상남도 양산시",
    "마산": "경상남도 창원시",  # 마산은 창원시에 통합
    # 군
    "의령": "경상남도 의령군",
    "함안": "경상남도 함안군",
    "창녕": "경상남도 창녕군",
    "고성": "경상남도 고성군",
    "남해": "경상남도 남해군",
    "하동": "경상남도 하동군",
    "산청": "경상남도 산청군",
    "함양": "경상남도 함양군",
    "거창": "경상남도 거창군",
    "합천": "경상남도 합천군",
}


def normalize_sigun(sigun: str) -> str:
    """부분 시군 이름을 'DB 저장 형태(경상남도 OO시/군)'로 정규화"""
    if not sigun:
        return sigun
    s = sigun.strip()
    if s in {"경남", "경남도", "경상남"}:
        return "경상남도"
    if s.startswith("경상남도 ") or s == "경상남도":
        return s
    key = re.sub(r'[시군]$', '', s)
    return _SIGUN_NORMALIZE_MAP.get(key, s)
